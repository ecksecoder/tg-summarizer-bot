"""Web content parsing and summarization module using native Google GenAI capabilities.

Delegates live web analysis and content extraction to Google AI via native prompt
instructions and Google Search Grounding tools, replacing legacy third-party
scraping libraries.
"""

import asyncio
import ipaddress
import logging
import os
import re
from typing import Any, Optional
from urllib.parse import urlparse

from google import genai
from google.genai import types
from pydantic import BaseModel, Field

logger = logging.getLogger(__name__)

FORMAT_INSTRUCTIONS: dict[str, str] = {
    "SHORT": (
        "OUTPUT FORMAT: ⚡ CHEAT SHEET (MAXIMAL COMPRESSION).\n"
        "- Length: strictly 5–10 most critical facts, takeaways, or figures.\n"
        "- Direct substance only: core events, findings, and conclusions without fluff."
    ),
    "MEDIUM": (
        "OUTPUT FORMAT: 📋 STRUCTURED SUMMARY (BALANCED DEPTH).\n"
        "- Divide the material into logical blocks with informative subheadings.\n"
        "- Preserve all key facts, storylines, data points, and cause-and-effect relationships."
    ),
    "LONG": (
        "OUTPUT FORMAT: 📚 COMPREHENSIVE BREAKDOWN (MAXIMUM DEPTH).\n"
        "- Detail every section or topic thoroughly in structured order.\n"
        "- Preserve nuances, concrete examples, arguments, and context so the summary "
        "replaces reading the entire source."
    ),
}

DEFAULT_SYSTEM_INSTRUCTION: str = (
    "You are an enterprise AI research analyst and content summarizer. "
    "Your objective is to analyze the content of the provided web link and produce "
    "a high-yield, structured summary without fluff, navigation noise, or filler. "
    "Respond in Russian using clear GitHub-flavored markdown formatting (bold headers, bullet points). "
    "Include a concise title at the very beginning."
)


def is_safe_url(url: str) -> tuple[bool, str]:
    """Validate target URL against SSRF vectors (loopback, private, and reserved IPs).

    Args:
        url: The web URL string to validate.

    Returns:
        tuple[bool, str]: (is_safe, error_reason)
    """
    try:
        parsed = urlparse(url)
    except Exception as exc:
        return False, f"Malformed URL: {exc}"

    if parsed.scheme not in ("http", "https"):
        return False, "Only HTTP and HTTPS protocols are allowed."

    hostname = (parsed.hostname or "").lower()
    if not hostname:
        return False, "Missing hostname in target URL."

    if hostname in ("localhost", "127.0.0.1", "::1", "0.0.0.0"):
        return False, "Access to localhost addresses is restricted."

    try:
        ip = ipaddress.ip_address(hostname)
        if ip.is_private or ip.is_loopback or ip.is_link_local or ip.is_reserved:
            return False, "Access to private or local network resources is restricted."
    except ValueError:
        # Hostname is a domain name rather than an IP literal
        pass

    return True, ""


class LinkSummaryResponse(BaseModel):
    """Structured response container for processed and summarized web links."""

    url: str = Field(description="The source URL analyzed.")
    title: str = Field(default="", description="Extracted or inferred title of the webpage.")
    summary: str = Field(description="Structured markdown summary generated by Google AI.")
    key_points: list[str] = Field(
        default_factory=list,
        description="Key takeaways or bullet points from the content.",
    )
    format_size: str = Field(
        default="MEDIUM",
        description="Compression tier requested (SHORT, MEDIUM, or LONG).",
    )
    model: str = Field(
        default="gemini-3.8-flash",
        description="The Google GenAI model used for analysis.",
    )
    grounding_metadata: dict[str, Any] = Field(
        default_factory=dict,
        description="Search Grounding metadata including search queries and source links.",
    )
    raw_text: str = Field(
        default="",
        description="Reference text content or raw extraction if available.",
    )

    def to_display_text(self) -> str:
        """Return formatted markdown text suitable for chat interface presentation.

        Returns:
            str: Markdown formatted summary string.
        """
        return self.summary

    def __str__(self) -> str:
        """Return the summary as string for backward-compatible string coercion.

        Returns:
            str: Markdown formatted summary string.
        """
        return self.summary


def _extract_title(text: str, fallback_url: str) -> str:
    """Extract a representative title from model output or fallback to hostname.

    Args:
        text: The generated summary text.
        fallback_url: URL to extract hostname from if no title is present.

    Returns:
        str: Cleaned title string.
    """
    for line in text.splitlines():
        line = line.strip()
        if line.startswith("#"):
            cleaned = line.lstrip("#").strip()
            if cleaned:
                return cleaned[:120]
        if line.startswith("**") and line.endswith("**") and len(line) > 4:
            return line.strip("*").strip()[:120]

    parsed = urlparse(fallback_url)
    return parsed.netloc or fallback_url


def _extract_key_points(text: str) -> list[str]:
    """Parse bullet points from generated markdown text.

    Args:
        text: The generated summary text.

    Returns:
        list[str]: Extracted bullet point takeaways.
    """
    bullets = []
    for line in text.splitlines():
        line = line.strip()
        if line.startswith(("- ", "* ", "• ")) and len(line) > 5:
            item = line[2:].strip()
            if item:
                bullets.append(item)
    return bullets[:10]


def _extract_grounding_metadata(response: Any) -> dict[str, Any]:
    """Extract grounding citations and web queries safely from candidate response.

    Args:
        response: The Google GenAI GenerateContentResponse object.

    Returns:
        dict[str, Any]: Extracted search queries and source references.
    """
    metadata: dict[str, Any] = {}
    try:
        candidates = getattr(response, "candidates", None)
        if candidates and len(candidates) > 0:
            candidate = candidates[0]
            g_meta = getattr(candidate, "grounding_metadata", None)
            if g_meta:
                if hasattr(g_meta, "web_search_queries") and g_meta.web_search_queries:
                    metadata["search_queries"] = list(g_meta.web_search_queries)
                if hasattr(g_meta, "grounding_chunks") and g_meta.grounding_chunks:
                    chunks = []
                    for c in g_meta.grounding_chunks:
                        web = getattr(c, "web", None)
                        if web:
                            chunks.append({
                                "uri": getattr(web, "uri", ""),
                                "title": getattr(web, "title", ""),
                            })
                    if chunks:
                        metadata["sources"] = chunks
    except Exception as exc:
        logger.debug("Failed to extract grounding metadata: %s", exc)
    return metadata


async def parse_and_summarize_url(
    url: str,
    format_size: str = "MEDIUM",
    client: Optional[genai.Client] = None,
    model: str = "gemini-3.8-flash",
    system_instruction: Optional[str] = None,
    temperature: float = 0.25,
    use_search_grounding: bool = True,
) -> LinkSummaryResponse:
    """Analyze and summarize web content from a URL using native Google GenAI.

    Delegates content retrieval and comprehension entirely to the Google AI model,
    leveraging native Google Search Grounding to parse live web contents without
    local scraping libraries.

    Args:
        url: The web URL to inspect and summarize.
        format_size: The target summary length tier ('SHORT', 'MEDIUM', 'LONG').
        client: Optional pre-configured Google GenAI client instance.
        model: Target Gemini model identifier (defaults to 'gemini-3.8-flash').
        system_instruction: Optional custom system instructions.
        temperature: Sampling temperature for generation.
        use_search_grounding: Whether to enable Google Search Grounding.

    Returns:
        LinkSummaryResponse: Structured object containing URL, title, summary,
        key points, and grounding metadata.

    Raises:
        ValueError: If the URL fails SSRF safety validation or API key is missing.
        RuntimeError: If Google GenAI invocation fails or returns empty output.
    """
    clean_url = url.strip()
    is_safe, reason = is_safe_url(clean_url)
    if not is_safe:
        raise ValueError(f"URL failed security validation: {reason}")

    # Standardize social/code hosting preview URLs for crawler accessibility
    if "t.me/" in clean_url and "/s/" not in clean_url:
        clean_url = re.sub(r"https?://t\.me/([^/]+)/(\d+)", r"https://t.me/s/\1/\2", clean_url)
    elif "github.com/" in clean_url and "/blob/" in clean_url:
        clean_url = clean_url.replace("github.com/", "raw.githubusercontent.com/").replace("/blob/", "/")

    # Initialize Google AI client if not provided
    if client is None:
        api_key = os.getenv("GEMINI_API_KEY", "").strip()
        if not api_key:
            raise ValueError("GEMINI_API_KEY is not set in environment.")
        client = genai.Client(api_key=api_key)

    # Configure Google Search Grounding tool
    tools = []
    if use_search_grounding:
        tools.append(types.Tool(google_search=types.GoogleSearch()))

    fmt_key = format_size.upper() if format_size.upper() in FORMAT_INSTRUCTIONS else "MEDIUM"
    size_guide = FORMAT_INSTRUCTIONS[fmt_key]

    prompt = (
        f"Analyze and extract key information from the following webpage URL: {clean_url}\n\n"
        f"Instructions:\n"
        f"1. Retrieve and examine the latest content from this web address.\n"
        f"2. Extract the primary title/headline of the article or page.\n"
        f"3. Generate a structured summary according to these specifications:\n"
        f"{size_guide}\n"
        f"4. Provide 3–7 core bullet points summarizing the most important takeaways."
    )

    config = types.GenerateContentConfig(
        system_instruction=system_instruction or DEFAULT_SYSTEM_INSTRUCTION,
        tools=tools if tools else None,
        temperature=temperature,
    )

    # Execute generation asynchronously via native async client or asyncio.to_thread
    try:
        if hasattr(client, "aio") and hasattr(client.aio, "models"):
            response = await client.aio.models.generate_content(
                model=model,
                contents=prompt,
                config=config,
            )
        else:
            response = await asyncio.to_thread(
                client.models.generate_content,
                model=model,
                contents=prompt,
                config=config,
            )
    except Exception as exc:
        logger.error("Google GenAI URL summarization failed for %s: %s", clean_url, exc)
        raise RuntimeError(f"Google GenAI processing failed: {exc}") from exc

    response_text = response.text or ""
    if not response_text.strip():
        raise RuntimeError(f"Google GenAI returned an empty response for URL: {clean_url}")

    title = _extract_title(response_text, clean_url)
    key_points = _extract_key_points(response_text)
    grounding_info = _extract_grounding_metadata(response)

    return LinkSummaryResponse(
        url=clean_url,
        title=title,
        summary=response_text.strip(),
        key_points=key_points,
        format_size=fmt_key,
        model=model,
        grounding_metadata=grounding_info,
        raw_text=response_text.strip(),
    )


# Alias for intuitive interface naming
process_link = parse_and_summarize_url


async def fetch_url_text(url: str, format_size: str = "MEDIUM") -> str:
    """Legacy compatibility bridge returning raw summary text for a URL.

    Args:
        url: Web URL to process.
        format_size: Compression tier for summary.

    Returns:
        str: Formatted summary text.
    """
    result = await parse_and_summarize_url(url, format_size=format_size)
    return result.summary
